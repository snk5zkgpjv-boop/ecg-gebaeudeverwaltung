import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const roomPrint=html.slice(html.indexOf('window.showAllRoomQRs=()=>'),html.indexOf('window.printRoomQRSheet='));
const styles=html.slice(html.indexOf('/* ECG transparent-film door inserts'),html.indexOf('.room-toolbar-actions{'));
const print=html.slice(html.indexOf('body.qr-print-mode .qr-sheet'),html.indexOf('\n}',html.indexOf('body.qr-print-mode .qr-sheet')));
assert.match(roomPrint,/qr-label-number/);
assert.match(roomPrint,/qr-label-watermark/);
assert.match(roomPrint,/qr-label-brand-text/);
assert.match(roomPrint,/embedded-4-8ef55a643706\.png/);
assert.match(roomPrint,/qr-label-qr/);
assert.ok(roomPrint.indexOf('qr-label-watermark') < roomPrint.indexOf('qr-label-qr'));
assert.doesNotMatch(roomPrint,/qr-label-meta|QR-ID:|Raum-ID:|ecg\.technik/i);
assert.match(styles,/background:transparent/);
assert.match(styles,/color:#8d153f/);
assert.match(print,/width:15mm!important;height:15mm!important/);
assert.match(print,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.doesNotMatch(print,/background:white|background:#fff/i);
console.log('PASS transparent room sign print: watermark, logo and text, bordeaux number, 15 mm lower-left QR, no footer');
